import * as Print from "expo-print";
import * as Sharing from "expo-sharing";
import type { Sale } from "./types";
import { money } from "./api";
export function escapeHtml(value: unknown) {
  return String(value ?? "").replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ]!,
  );
}
export function receiptHtml(sale: Sale) {
  const e = escapeHtml;
  return `<!doctype html><html><head><meta charset="utf-8"><style>body{font-family:Arial,sans-serif;padding:28px;color:#173122}h1{font-size:24px}table{width:100%;border-collapse:collapse;margin:24px 0}td,th{text-align:left;padding:12px 4px;border-bottom:1px solid #ddd}.number{text-align:right}footer{margin-top:30px;color:#666;font-size:12px}</style></head><body><h1>${e(sale.business_name)}</h1><p>Bill ${e(sale.number)} · ${e(new Date(sale.created_at).toLocaleString())}</p><p>Cashier: ${e(sale.cashier_name)}<br>Customer: ${e(sale.customer_name || "Walk-in")}${sale.customer_phone ? " · " + e(sale.customer_phone) : ""}</p><table><tr><th>Product</th><th>Qty</th><th class="number">Amount</th></tr>${sale.items.map((i) => `<tr><td>${e(i.name)}</td><td>${e(i.quantity)} ${e(i.unit)}</td><td class="number">${e(money(i.line_total, sale.currency))}</td></tr>`).join("")}</table><p>Subtotal: ${e(money(sale.subtotal, sale.currency))}<br>Discount: ${e(money(sale.discount, sale.currency))}</p><h2>Total: ${e(money(sale.total, sale.currency))}</h2><p>Payment: ${e(sale.payment_method.toUpperCase())}</p>${
    sale.returns.length
      ? `<p>Returns: ${e(
          money(
            sale.returns.reduce((sum, r) => sum + Number(r.amount), 0),
            sale.currency,
          ),
        )}</p>`
      : ""
  }<footer>Generated by Stoqo. Thank you for shopping with us.</footer></body></html>`;
}
export async function shareReceipt(sale: Sale) {
  const result = await Print.printToFileAsync({ html: receiptHtml(sale) });
  if (await Sharing.isAvailableAsync())
    await Sharing.shareAsync(result.uri, {
      mimeType: "application/pdf",
      dialogTitle: `Bill ${sale.number}`,
      UTI: "com.adobe.pdf",
    });
  else await Print.printAsync({ html: receiptHtml(sale) });
}
